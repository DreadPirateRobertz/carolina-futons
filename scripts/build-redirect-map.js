#!/usr/bin/env node
/**
 * cf-3qt.7 prep — build a 301 redirect map from the GSC URL dump.
 *
 * Reads scripts/gsc-indexed-urls.json (produced by gsc-url-pull.js), applies
 * a set of Wix-to-Next transforms, and emits scripts/redirect-map.json plus
 * a Next.js redirects() array in scripts/next-redirects.generated.ts ready to
 * import into next.config.ts.
 *
 * Transforms covered:
 *   /product-page/<slug>          → /products/<slug>
 *   /product-page?product=<slug>  → /products/<slug>   (legacy Wix query form)
 *   /post/<slug>                  → /blog/<slug>
 *   /category/<slug>              → /category/<slug>   (identity — no-op, kept for clarity)
 *   /account/my-<x>               → /account/<x>
 *   /thank-you-page               → /order-confirmation
 *   /cart-page                    → /cart
 *   /search-results               → /search
 *   /sitemap                      → /sitemap.xml
 *
 * Unmapped URLs land in `unmapped` — they need a manual review pass.
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const IN_PATH     = path.join(__dirname, 'gsc-indexed-urls.json');
const OUT_JSON    = path.join(__dirname, 'redirect-map.json');
const OUT_NEXT_TS = path.join(__dirname, 'next-redirects.generated.ts');

const RULES = [
  { match: /^\/product-page\/([^/?#]+)/,   to: (m) => `/products/${m[1]}` },
  { match: /^\/product-page\/?\?product=([^&]+)/, to: (m) => `/products/${decodeURIComponent(m[1])}` },
  { match: /^\/post\/([^/?#]+)/,           to: (m) => `/blog/${m[1]}` },
  { match: /^\/account\/my-orders/,        to: ()  => '/account/orders' },
  { match: /^\/account\/my-wishlist/,      to: ()  => '/account/wishlist' },
  { match: /^\/account\/my-account/,       to: ()  => '/account' },
  { match: /^\/thank-you-page/,            to: ()  => '/order-confirmation' },
  { match: /^\/cart-page/,                 to: ()  => '/cart' },
  { match: /^\/search-results/,            to: (_, full) => full.replace(/^\/search-results/, '/search') },
  { match: /^\/sitemap\/?$/,               to: ()  => '/sitemap.xml' },
];

function toPath(urlStr) {
  try {
    // GSC returns absolute URLs for https://… properties and paths for sc-domain
    return new URL(urlStr, 'https://x.local').pathname + (new URL(urlStr, 'https://x.local').search || '');
  } catch {
    return urlStr;
  }
}

function map(pathWithQuery) {
  for (const rule of RULES) {
    const m = pathWithQuery.match(rule.match);
    if (m) return rule.to(m, pathWithQuery);
  }
  return null;
}

async function main() {
  const raw = await fs.readFile(IN_PATH, 'utf-8').catch(() => null);
  if (!raw) {
    console.error(`[redirect] Missing ${IN_PATH}. Run scripts/gsc-url-pull.js first.`);
    process.exit(2);
  }
  const dump = JSON.parse(raw);

  const mapped   = [];
  const unmapped = [];

  for (const row of dump.urls) {
    const source = toPath(row.url);
    const destination = map(source);
    if (destination && destination !== source) {
      mapped.push({ source, destination, impressions: row.impressions, clicks: row.clicks });
    } else if (!destination) {
      unmapped.push({ source, impressions: row.impressions, clicks: row.clicks });
    }
  }

  // Dedupe mapped by source — GSC can emit duplicates across date ranges.
  const dedup = new Map();
  for (const r of mapped) dedup.set(r.source, r);
  const finalRedirects = [...dedup.values()].sort((a, b) => b.impressions - a.impressions);

  const report = {
    builtAt: new Date().toISOString(),
    source:  dump.fetchedAt,
    counts:  { total: dump.urls.length, mapped: finalRedirects.length, unmapped: unmapped.length },
    redirects: finalRedirects,
    unmapped: unmapped.slice(0, 200),                          // cap — full list often noisy
  };
  await fs.writeFile(OUT_JSON, JSON.stringify(report, null, 2));

  const tsBody = [
    '// Generated by scripts/build-redirect-map.js — do not hand-edit.',
    `// Source: ${dump.fetchedAt}  (${finalRedirects.length} rules)`,
    '',
    'import type { Redirect } from \'next/dist/lib/load-custom-routes\';',
    '',
    'export const legacyRedirects: Redirect[] = [',
    ...finalRedirects.map(r =>
      `  { source: ${JSON.stringify(r.source)}, destination: ${JSON.stringify(r.destination)}, permanent: true },`
    ),
    '];',
    '',
  ].join('\n');
  await fs.writeFile(OUT_NEXT_TS, tsBody);

  console.log(`[redirect] ${finalRedirects.length} rules → ${OUT_NEXT_TS}`);
  console.log(`[redirect] ${unmapped.length} unmapped URLs need manual review (see ${OUT_JSON})`);
}

main().catch(e => { console.error('[redirect] fatal:', e); process.exit(2); });
